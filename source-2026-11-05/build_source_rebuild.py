FIRA_BLOCK = r"""% ---- FONT RULE (exact, per rebuild brief; Fira only, Noto fallback) ----
% Fira Sans for text, Fira Mono for code, Fira Math for math (Scale=1.15).
% No synthetic bold is used anywhere in this file. Bold faces are pinned by
% filename to the real weights (see below): fontspec's default resolution for
% this family maps \textbf to ExtraBold, which is real but not the intended
% Bold weight, so the pins below are load-bearing, not cosmetic.
\setmainfont{Fira Sans}[BoldFont=FiraSans-Bold.otf,ItalicFont=FiraSans-Italic.otf,BoldItalicFont=FiraSans-BoldItalic.otf]
\setsansfont{Fira Sans}[BoldFont=FiraSans-Bold.otf,ItalicFont=FiraSans-Italic.otf,BoldItalicFont=FiraSans-BoldItalic.otf]
\setmonofont{Fira Mono}[BoldFont=FiraMono-Bold.otf]
\setmathfont{Fira Math}[Scale=1.15]
% Math bold: Fira Math ships Regular only (no Bold weight exists in this
% TeX Live tree), so no bold math version is declared. \mathbf therefore
% renders in the regular math weight via unicode-math's fallback --- it is
% NOT synthesized (no poor-man's-bold overprinting anywhere).
% Fallback for missing glyphs ONLY (cmap evidence, fontTools):
%  U+2208 (in)      : PRESENT in Fira Math -> needs no fallback.
%  U+2216 (setminus): ABSENT in Fira Math, PRESENT in Noto Sans Math -> fallback:
\setmathfont{Noto Sans Math}[range={"2216},Scale=1.15]
%  U+2090 (subscript a): ABSENT in Fira Sans, Fira Math and Noto Sans Math,
%  PRESENT in Noto Sans -> text-mode fallback via an explicit font switch
%  ({\notosans <glyph>}) at the single site where the glyph is used:
\newfontfamily{\notosans}{Noto Sans}
%  U+2124 (Z, double-struck): ABSENT in Fira Sans (text mode), PRESENT in
%  Fira Math and Noto Sans. The two literal text-mode occurrences render via
%  the math double-struck Z (same glyph, math mode):
\usepackage{newunicodechar}
\newunicodechar{ℤ}{$\mathbb{Z}$}"""

