def extract_expansions(text):
    """Return the bodies of all \\expansion{...} calls except the \\newcommand."""
    out = []
    i = 0
    while True:
        j = text.find("\\expansion{", i)
        if j < 0:
            break
        # skip the \newcommand definition line
        line_start = text.rfind("\n", 0, j) + 1
        if "\\newcommand" in text[line_start:j]:
            i = j + 1
            continue
        depth = 0
        k = j + len("\\expansion")
        assert text[k] == "{", text[k:k + 20]
        start = k + 1
        k = start
        while True:
            c = text[k]
            if c == "{":
                depth += 1
            elif c == "}":
                if depth == 0:
                    break
                depth -= 1
            k += 1
        out.append(text[start:k])
        i = k + 1
    return out


def adapt(body):
    """Adapt a PDF-rebuild expansion body to the source rebuild."""
    body = body.replace(
        "confirming $\\sqrt{2}$ and refuting $2$",
        "confirming $\\sqrt{2}$; the source already states $\\sqrt{2}$ here and in "
        "the abstract and \\S VI-A.1, and the shipped PDF renders $\\sqrt{2}$ --- "
        "the ``$2$'' in the earlier PDF-rebuild was a pdftotext-layout artifact "
        "(the radical prints on its own layout line), not a source error",
    )
    body = body.replace(
        "in the extracted text",
        "in the source text",
    )
    return body


def main():
    src = SRC.read_text(encoding="utf-8")
    rb = PDFREBUILD.read_text(encoding="utf-8")
    expansions = extract_expansions(rb)
    print(f"extracted {len(expansions)} expansions from PDF-rebuild")
    assert len(expansions) == 26, len(expansions)
    assert len(ANCHORS) == 26, len(ANCHORS)
    expansions = [adapt(b) for b in expansions]

    # --- 1. font block replacement ---
    m = re.search(
        r"% Bundled fonts \(fonts/\) so the source compiles on Overleaf as-is\.\n"
        r"\\setmainfont\{NotoSans-Regular\.ttf\}\[Path=fonts/,BoldFont=NotoSans-Bold\.ttf,"
        r"ItalicFont=NotoSans-Italic\.ttf,BoldItalicFont=NotoSans-BoldItalic\.ttf\]\n"
        r"\\setmonofont\{NotoSansMono-Regular\.ttf\}\[Path=fonts/\]\n"
        r"% Math: Latin Modern Math supplies the OpenType MATH table \(layout\);\n"
        r"% Noto Sans Math supplies the visible glyphs \(this build's Noto Sans Math\n"
        r"% has no MATH table, so it is overlaid by range on the LM base\)\.\n"
        r"\\setmathfont\{Latin Modern Math\}\n"
        r"\\setmathfont\{NotoSansMath-Regular\.ttf\}\[Path=fonts/,range=\{up/\{latin,Latin,num\},"
        r"it/\{latin,Latin\},up/\{greek,Greek\},it/\{greek,Greek\},bfup/\{latin,Latin,greek,Greek,num\},"
        r"bfit/\{latin,Latin,greek,Greek\},\"2192,\"2208,\"2212,\"223C,\"2248,\"2273\}\]",
        src,
    )
    assert m, "font block not found"
    src = src[: m.start()] + FIRA_BLOCK + src[m.end():]

    # --- 2. hyperref defects (abstract, line 45) ---
    assert src.count("\\\\hyperref[ref-40]{[40]}") == 1
    src = src.replace("\\\\hyperref[ref-40]{[40]}", "\\hyperref[ref40]{[40]}")
    for n in (1, 2, 3):
        old = f"\\hyperref[ref-{n}]{{[{n}]}}"
        assert src.count(old) == 1, (old, src.count(old))
        src = src.replace(old, f"\\hyperref[ref{n}]{{[{n}]}}")
    assert "ref-" not in src, "dashed ref labels remain"

    # --- 3. expansion command definitions before \begin{document} ---
    assert "\\begin{document}" in src
    src = src.replace("\\begin{document}", EXPANSION_CMD + "\n\n\\begin{document}", 1)

    # --- 4. front matter after the abstract ---
    assert "\\end{abstract}" in src
    src = src.replace("\\end{abstract}", "\\end{abstract}\n" + FRONT_MATTER, 1)

    # --- 5. insert expansions after the paragraph containing each anchor ---
    lines = src.split("\n")
    # process anchors from last to first so line indices stay valid
    placed = []
    for idx in range(len(ANCHORS) - 1, -1, -1):
        anchor = ANCHORS[idx]
        hits = [i for i, ln in enumerate(lines) if anchor in ln]
        assert len(hits) == 1, (idx, anchor, len(hits))
        h = hits[0]
        # insert after the next blank line following the anchor line
        j = h
        while j < len(lines) and lines[j].strip() != "":
            j += 1
        ins = "\\expansion{" + expansions[idx] + "}"
        lines[j + 1:j + 1] = ["", ins]
        placed.append(idx)
    assert sorted(placed) == list(range(26))
    out = "\n".join(lines)
    assert out.count("\\expansion{") == 26, out.count("\\expansion{")
    assert "FakeBold=" not in out
    OUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUT} ({len(out.splitlines())} lines, {len(out)} bytes)")


if __name__ == "__main__":
    main()
