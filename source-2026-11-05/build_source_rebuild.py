FRONT_MATTER = r"""
\section*{Source rebuild --- read first}

\noindent\textit{Font check (rebuild apparatus):} $x \in A \setminus B$, subscript-a glyph {\notosans ₐ}, $D_4$, $\tau$, $q_4$. All three required glyphs (U+2208, U+2216, U+2090) render in this document: $\in$ from Fira Math, $\setminus$ from the Noto Sans Math fallback, {\notosans ₐ} from the Noto Sans text fallback.

This document is a rebuild of IRH v93.1 from the author's supplied source package (2026-11-05), not from PDF extraction. The authoring source is the Markdown manuscript \texttt{paper\_v931.md}; the shipped \texttt{IRH\_v93\_1.tex} is generated from it by the supplied \texttt{md2tex.py}, which regenerates the shipped \texttt{.tex} byte-identically (verified 2026-11-05). The shipped \texttt{.tex} is used here as the base, verbatim except for the items below. The ten supplied figures \texttt{figs/fig01--fig10.png} are used as-is.

\textbf{Font rule.} Fira Sans (text), Fira Mono (code), Fira Math (math, Scale=1.15), no synthetic bold; Noto Sans / Noto Sans Math fallback for missing glyphs only (grounded in fontTools cmap evidence). The shipped source used Noto Sans / Latin Modern Math with a \texttt{fonts/} directory that is \textit{not} in the supplied package, so the shipped \texttt{.tex} does not compile as-shipped in this environment; the Fira substitution also repairs that.

\textbf{``Expansion (source rebuild)'' passages} show step-by-step arithmetic the source text skips. They add no new physical claim. Every number in them was verified in this leg with SymPy 1.14.0, with python-flint / Singular as second tool for load-bearing claims; see the rebuild log.

\textbf{Two open questions from the earlier PDF-rebuild, answered from the source \texttt{.tex}:}

\begin{itemize}
\item \textbf{The 11.85\% vs 11.90\% band (\S II.7).} The source genuinely contains both values; this is \textit{not} a PDF-text garble. The headline \textbf{PREDICTION} states 11.85\% of the scanned plane, and the qualification states ``This qualification must accompany every citation of the 11.85\% figure.'' The sixth-order paragraph then states ``(11.90\% at $w_6=0$ to 8.47\% at $w_6=0.2$)\ldots The $w_6=0$ value independently reproduces the 11.85\% obtained by different code'' --- so the $w_6=0$ band value is stated as both 11.90\% and 11.85\%, and Appendix A item 8 calls 11.9\% ``the correct'' value. The discrepancy is 0.05 percentage points, consistent with two code paths differing in rounding, but the source does not say that. \textbf{This rebuild keeps 11.85\% as the headline figure and flags the inconsistency; it does not resolve it.} Which value is canonical is a decision for the author.
\item \textbf{$\tau_{D_4}/\tau_{\mathrm{BCC}}$.} The source \texttt{.tex} states $\sqrt{2}$ everywhere: abstract, \S II.5 (``in ratio exactly $\sqrt2$''), and \S VI-A.1. The shipped PDF renders $\sqrt{2}$ as well; the earlier PDF-rebuild's ``correction'' of a stated $2$ addressed a pdftotext-layout artifact (the radical prints on its own layout line), not a source error. \textbf{No correction was needed or made here.} The exact ratio $\tau_{D_4}/\tau_{\mathrm{BCC}}=\sqrt{2}$ is verified symbolically in this leg.
\end{itemize}

\textbf{Source defects fixed in this rebuild (all present in the shipped PDF as well).} In the abstract, the shipped \texttt{.tex} contains \texttt{\textbackslash\textbackslash hyperref[ref-40]\{[40]\}} (double backslash, dashed label), which renders literally as ``hyperref[ref-40][40]'' in the shipped PDF; it is corrected here to \texttt{\textbackslash hyperref[ref40]\{[40]\}}. The same sentence's \texttt{[ref-1]}, \texttt{[ref-2]}, \texttt{[ref-3]} use dashed labels that do not exist (labels are \texttt{ref1}, \texttt{ref2}, \texttt{ref3}); they are corrected to the undashed labels. No other manuscript text was altered.

\textbf{Grade discipline (HLRE v5).} No claim's grade is changed by this rebuild. The D$_4$/triality/2T--McKay--E$_6$/Swift--Hohenberg mathematics is Grade A; the physical/substrate reading is graded $\le$ C/D; three generations is an INPUT, not a derived result; Perelman's $\tau$ is not IRH's $\tau$; $S=64/141$ is shell combinatorics, not an entropy, and is never identified with Perelman's $W$.
"""

