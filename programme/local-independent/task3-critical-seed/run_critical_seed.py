#!/usr/bin/env python3
"""Task 3 (local-independent): critical D4 seed in the full 4D field.

Reuses the exact dealiased Fourier-Galerkin Field / ETD2 integrator from
the prior 4D field test (run_field_study.py) by import -- no code copied,
no Co-scientist output read. Seeds are localized D4 patches in real space:
  psi(x) = mean + alpha*A* * env(rho) * sum_{g in D4 shell} cos(g.x),
  env = 0.5*(1 - tanh(sharp*(rho - R))), sharp = 4.0 (Task-4 droplet form),
  rho = Euclidean distance from the box centre, box L = 2*pi, mean = -0.18.
The seed is projected onto the retained band |k_i| <= 4 before evolution,
so harmonics / unequal modes are free to evolve (they are generated by the
real-space envelope x carrier product). Growth / dissolve classification
uses the field-test outcome() rule on the final saved state.

Usage:
  python run_critical_seed.py --out . --alpha 1.0 --radii 0.6 0.9 1.2 ...
      [--t-final 200 --dt 0.1 --n 18 --cutoff 4 --tag coarse_a1]
  Each run appends one row to <out>/seed_outcomes.csv and one row per saved
  time to <out>/seed_trajectories.csv, and writes <out>/<run_id>.npz with
  the initial/final compact coefficients.
Seed for run identity: deterministic from (alpha, R, n, cutoff, dt) -- no RNG.
"""
import argparse, csv, hashlib, importlib.util, json, sys, time
from pathlib import Path
import numpy as np

FIELD_SRC = Path.home() / "workspace/research/irh/co-scientist-tasks-2026-11-10/4d-field-test/run_field_study.py"
MEAN = -0.18
A_STAR = 0.07757529633928076  # exact one-mode amplitude, verified in-script
SHARP = 4.0
LBOX = 2 * np.pi


def load_field_module():
    spec = importlib.util.spec_from_file_location("field_study", FIELD_SRC)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build_seed(m, kstar, alpha, radius):
    """Return (y, info): projected Fourier coefficients of the localized seed."""
    n = m.n
    xs = np.linspace(0.0, LBOX, n, endpoint=False)
    X1, X2, X3, X4 = np.meshgrid(xs, xs, xs, xs, indexing="ij")
    d2 = ((X1 - np.pi) ** 2 + (X2 - np.pi) ** 2 + (X3 - np.pi) ** 2 + (X4 - np.pi) ** 2)
    rho = np.sqrt(d2)
    env = 0.5 * (1.0 - np.tanh(SHARP * (rho - radius)))
    pattern = np.zeros_like(X1)
    for g in kstar:
        pattern += np.cos(g[0] * X1 + g[1] * X2 + g[2] * X3 + g[3] * X4)
    psi = MEAN + alpha * A_STAR * env * pattern
    psi += (MEAN - psi.mean())  # restore exact conserved mean
    phi = psi - MEAN
    y = m.fft(phi) * m.mask
    # Effective radius from the envelope volume: R_eq = (2*V_env/pi^2)^(1/4),
    # V_env = int env^2 d^4x (sharp-ball equivalent radius).
    dx = LBOX / n
    v_env = float(np.sum(env ** 2) * dx ** 4)
    r_eq = (2.0 * v_env / np.pi ** 2) ** 0.25
    info = dict(
        radius=float(radius), alpha=float(alpha), sharp=SHARP,
        r_eq=float(r_eq), env_volume=float(v_env),
        seed_mean=float(psi.mean()), seed_rms=float(np.sqrt(np.mean(phi ** 2))),
        projected_power=float(np.sum(m.weight * np.abs(y) ** 2)),
    )
    return y, info


def run_one(mod, out, alpha, radius, t_final, dt, n, cutoff, tag):
    m = mod.Field(n, cutoff)
    y0, info = build_seed(m, mod.KSTAR, alpha, radius)
    tick = time.perf_counter()
    yf, rows, shell, spectra, stats = mod.integrate(m, y0, dt, t_final)
    elapsed = time.perf_counter() - tick
    final = rows[-1]
    oc = mod.outcome(final)
    run_id = f"{tag}_a{alpha:g}_R{radius:g}"
    row = dict(
        run_id=run_id, tag=tag, alpha=alpha, radius_nominal=radius,
        r_eq=info["r_eq"], env_volume=info["env_volume"],
        n=n, cutoff=cutoff, dt=dt, t_final=t_final,
        initial_rms=rows[0]["modulation_rms"],
        initial_shell_fraction=rows[0]["shell_fraction"],
        initial_energy=rows[0]["excess_energy"],
        initial_shell_power=rows[0]["shell_power"],
        initial_off_shell_power=rows[0]["off_shell_power"],
        outcome=oc, final_time=final["time"],
        final_rms=final["modulation_rms"],
        final_shell_fraction=final["shell_fraction"],
        final_energy=final["excess_energy"],
        final_occupancy=final["occupancy"],
        final_cv=final["amplitude_cv"], final_lock=final["triad_lock"],
        final_rhs_rms=final["rhs_rms"],
        final_off_shell_power=final["off_shell_power"],
        accepted_steps=stats["accepted_steps"],
        rejected_steps=stats["rejected_steps"],
        max_step_energy_increase=stats["max_step_energy_increase"],
        elapsed_seconds=elapsed,
    )
    # trajectories
    traj_path = out / "seed_trajectories.csv"
    traj_rows = [dict(run_id=run_id, tag=tag, alpha=alpha, radius_nominal=radius, **r)
                 for r in rows]
    write_csv(traj_path, traj_rows, append=True)
    write_csv(out / "seed_outcomes.csv", [row], append=True)
    np.savez_compressed(
        out / f"{run_id}.npz",
        wavevectors=m.compactK,
        initial_coefficients=m.coefficients(y0, m.compactK),
        final_coefficients=m.coefficients(yf, m.compactK),
        times=np.array([r["time"] for r in rows]),
        shell_coefficients=shell, power_by_k_squared=spectra)
    print(json.dumps({k: row[k] for k in
                      ["run_id", "outcome", "initial_rms", "initial_shell_fraction",
                       "initial_energy", "final_rms", "final_energy", "final_occupancy",
                       "final_rhs_rms", "elapsed_seconds", "rejected_steps"]}), flush=True)
    return row


def write_csv(path, rows, append=False):
    mode = "a" if (append and path.exists()) else "w"
    with path.open(mode, newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        if mode == "w":
            w.writeheader()
        w.writerows(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=".")
    ap.add_argument("--alpha", type=float, default=1.0)
    ap.add_argument("--radii", type=float, nargs="+", required=True)
    ap.add_argument("--t-final", type=float, default=200.0)
    ap.add_argument("--dt", type=float, default=0.1)
    ap.add_argument("--n", type=int, default=18)
    ap.add_argument("--cutoff", type=int, default=4)
    ap.add_argument("--tag", default="coarse")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    mod = load_field_module()
    # Verify A* independently (exact one-mode stationary amplitude):
    # f(A) = 12*0.1072*A^2 - 64*1.54*A^3 + 846*A^4 ; stationary root.
    # (N/2=12, T/3=64, Q/4=846.) Check via numpy roots in the report script,
    # here assert the imported value reproduces the field-test analytic A.
    assert abs(A_STAR - mod.A) < 1e-12, (A_STAR, mod.A)
    print(f"field module A* = {mod.A:.17g} ; script A* = {A_STAR:.17g} ; match OK",
          flush=True)
    print(f"field src sha256 = {hashlib.sha256(FIELD_SRC.read_bytes()).hexdigest()}",
          flush=True)
    for r in args.radii:
        run_one(mod, out, args.alpha, r, args.t_final, args.dt,
                args.n, args.cutoff, args.tag)


if __name__ == "__main__":
    main()
