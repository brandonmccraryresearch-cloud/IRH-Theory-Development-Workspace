# ------------------------------------------------------------------ 2. Cubic correction
# f3 = 2 A^2 sum_g (g^T eps g)(g^T eps^2 g)   [O(eps^3) term of gradient term]
def f2_f3(eps):
    eps = np.asarray(eps, dtype=float)
    eps2 = eps @ eps
    s2 = sum((np.array(g, dtype=float) @ eps @ np.array(g, dtype=float)) ** 2
             for g in SHELL)
    s3 = sum((np.array(g, dtype=float) @ eps @ np.array(g, dtype=float))
             * (np.array(g, dtype=float) @ eps2 @ np.array(g, dtype=float))
             for g in SHELL)
    return 2 * A2 * s2, 2 * A2 * s3

