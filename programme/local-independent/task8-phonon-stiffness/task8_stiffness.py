def crossover(Kb, r0b, n, Ke, r0e):
    """Radius R* where Kb ln(R/r0b) = n Ke ln(R/r0e); None if no crossing
    (asymptotically decided by the core logs)."""
    if abs(Kb - n * Ke) < 1e-12:
        return None
    L = (Kb * math.log(r0b) - n * Ke * math.log(r0e)) / (Kb - n * Ke)
    return math.exp(L)


