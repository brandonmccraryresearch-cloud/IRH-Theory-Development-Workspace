"""Task 8 — D4 phonon stiffness and Burgers-vector costs (local, independent).

Derivation (see REPORT.md for the full checkable steps):
  Functional F[psi] = int d^4x [ 1/2 psi (r + (q0^2 + nabla^2)^2) psi
    - (u/3) psi^3 + (v/4) psi^4 ], r = -0.35, u = v = 1, q0^2 = 8,
    psibar = -0.18, A* = larger root of alpha - 8*beta*A + 141*A^2 = 0
    with alpha = 0.1072, beta = 1.54.
  Phase-only deformation: psi(x) = psibar + A* sum_g exp(i g.(x + u(x))),
    g in the 24 scaled roots, |g|^2 = 8.  Local wavevector
    k_g = g + (grad u)^T g, |k_g|^2 = 8 + 2 g^T eps g + O(|grad u|^2)
    with eps = symmetric strain.  Gradient term gives, to O(eps^2),
    dF/V = 2 A^2 sum_g (g^T eps g)^2, and sum_g (g^T eps g)^2 is evaluated
    exactly (SymPy + direct numeric sum) as 128 Tr(eps^2) + 64 (Tr eps)^2,
    hence Lame lambda = mu = 256 A^2.
  Cubic (anharmonic) correction: dF/V at O(eps^3) from the same gradient
    term, evaluated exactly per strain state.
  Burgers vectors: D4 lattice {x in Z^4 : sum x_i even}; classes are
    orbits under the full lattice automorphism group W(F4), generated by
    signed permutations + one Hadamard (triality) matrix; group order is
    verified by exact-rational BFS closure (expect 1152).
  Dislocation sheet: u = (b/2 pi) theta in the transverse 2-plane.
    Angle-averaged energy density depends on the character of b relative
    to the sheet: with b = b_e + b_s (b_e in the transverse plane = edge
    part, b_s in the sheet plane = screw part),
        <f> = A^2 (64 |b_e|^2 + 32 |b_s|^2) / (pi^2 r^2),
    verified numerically for edge, screw and mixed orientations below.
    E / sheet-area = (128 A^2 / pi) (|b_e|^2 + |b_s|^2/2) ln(R / r0),
    with core radius r0 from energy-density balance <f>(r0) = |F|/V.

Deterministic: fixed seeds (rng seed 20261114). No randomness in the
headline numbers except the stated random-strain / random-direction checks.
"""
