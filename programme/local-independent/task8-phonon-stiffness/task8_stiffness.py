def orbits(vectors, grp):
    seen = set()
    orbs = []
    for v in vectors:
        if v in seen:
            continue
        orb = {mat_vec(g, v) for g in grp}
        orbs.append(orb)
        seen |= orb
    return orbs

# Lattice vectors with |b|^2 <= 12
